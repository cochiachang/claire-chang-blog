- 簡單表單也先寫程式，增加維護成本。
- 第一次授權時未檢查要求的權限。
- 修改程式後沒有重新執行或更新部署。

若工作涉及正式財務、法遵、薪資、交易、大量多人使用或高可用性要求，應加入正式審核、權限、測試、記錄與稽核機制，不能只依賴教學用試算表原型。

